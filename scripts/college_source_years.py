"""Kyle 2026-11-18: which championship years we have source documents for — the PDFs in
~/Desktop/wrestling_brackets/NCAA Tournament/{Mens,Womens}/<level>/ — written to src/lib/ncaa/sourceYears.ts for the
admin Progress grid (a year with no document is black). Rerun after adding files, then deploy.
   python3 scripts/college_source_years.py"""
import os, re
ROOT = os.path.expanduser('~/Desktop/wrestling_brackets/NCAA Tournament')
LEVEL = {'NCAA DI': 'NCAA DI', 'NCAA DII': 'NCAA DII', 'NCAA DIII': 'NCAA DIII', 'NAIA': 'NAIA', 'NCWWC': 'NCWWC', 'NCAA': 'NCAA'}
# file names that don't spell their year
ODD = {'NAIA_M_202.pdf': 2020}
# (NJCAA left out — Kyle 2026-11-18: "remove njcaa thats too much")
out = {'M': {}, 'F': {}}
for side, folder in (('M', 'Mens'), ('F', 'Womens')):
    base = os.path.join(ROOT, folder)
    if not os.path.isdir(base): continue
    for d in sorted(os.listdir(base)):
        if d not in LEVEL or not os.path.isdir(os.path.join(base, d)): continue
        out[side].setdefault(LEVEL[d], set())
        for f in os.listdir(os.path.join(base, d)):
            if not f.lower().endswith('.pdf'): continue
            m = re.search(r'(?<!\d)(19[2-9]\d|20[0-4]\d)(?!\d)', f)
            y = ODD.get(f) or (int(m.group(1)) if m else None)
            if not y: continue
            # the wrestlingstats place sheets name their division ("NCAA II 1985.pdf" sits in the DIII folder)
            lv = 'NCAA DII' if f.startswith('NCAA II ') else 'NCAA DIII' if f.startswith('NCAA III ') else LEVEL[d]
            out[side].setdefault(lv, set()).add(y)
    out[side] = {lv: sorted(ys) for lv, ys in out[side].items()}
lines = ["// Generated by scripts/college_source_years.py (Kyle 2026-11-18) — the championship years we have source documents",
         "// for (the PDFs in NCAA Tournament/{Mens,Womens}/<level>/). The admin Progress grid shows a year with none in black.",
         "// Rerun the script after adding files.",
         "export const SOURCE_YEARS: Record<'M' | 'F', Record<string, number[]>> = {"]
for side in ('M', 'F'):
    lines.append(f"  {side}: {{")
    for lv, ys in out[side].items(): lines.append(f"    '{lv}': [{', '.join(map(str, ys))}],")
    lines.append("  },")
lines.append("}")
open(os.path.join(os.path.dirname(__file__), '..', 'src', 'lib', 'ncaa', 'sourceYears.ts'), 'w').write('\n'.join(lines) + '\n')
print({s: {k: len(v) for k, v in o.items()} for s, o in out.items()})
